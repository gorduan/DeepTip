#!/usr/bin/env node
// Copies DeepTip (and the example) into an RPG Maker MZ project. Every file it replaces is kept as <file>.bak.
//
//   node frameworks/rpgmaker-mz/example/install.mjs <MZ project folder>                the example: HUD, demo glossary
//   node frameworks/rpgmaker-mz/example/install.mjs <MZ project folder> --plugin-only  DeepTip and the core glossary
//
// Works from the repository and from the download zip (both have frameworks/, glossary/ side by side).
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync, copyFileSync } from "node:fs";
import { dirname, join, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const args = process.argv.slice(2);
const pluginOnly = args.includes("--plugin-only");
const target = args.find((a) => !a.startsWith("--"));

if (!target || !existsSync(join(target, "js", "rmmz_core.js"))) {
  console.error("usage: node install.mjs <RPG Maker MZ project folder> [--plugin-only]");
  console.error(target ? `not an RPG Maker MZ project (js/rmmz_core.js missing): ${target}` : "no project folder given");
  process.exit(1);
}
const project = resolve(target);

function backup(file) {
  let bak = `${file}.bak`;
  for (let n = 2; existsSync(bak); n++) bak = `${file}.bak${n}`;
  copyFileSync(file, bak);
  return bak;
}

function put(file, data) {
  const dest = join(project, file);
  mkdirSync(dirname(dest), { recursive: true });
  if (existsSync(dest)) {
    if (Buffer.compare(readFileSync(dest), data) === 0) return console.log(`  same     ${file}`);
    console.log(`  replaced ${file} (old: ${relative(project, backup(dest))})`);
  } else console.log(`  added    ${file}`);
  writeFileSync(dest, data);
}

const copy = (from, to) => put(to, readFileSync(join(root, from)));
const jsonFiles = (dir) => readdirSync(join(root, dir)).filter((f) => f.endsWith(".json"));

console.log(`DeepTip -> ${project}`);
copy("frameworks/rpgmaker-mz/js/plugins/DeepTip.js", "js/plugins/DeepTip.js");
copy("frameworks/web/deeptip.js", "js/libs/deeptip.js");
copy("frameworks/web/deeptip.css", "css/deeptip.css");
for (const f of jsonFiles("glossary/core")) copy(`glossary/core/${f}`, `data/deeptip/core/${f}`);
if (!pluginOnly) {
  copy("frameworks/rpgmaker-mz/example/js/plugins/DeepTipDemo.js", "js/plugins/DeepTipDemo.js");
  for (const f of jsonFiles("glossary/example")) copy(`glossary/example/${f}`, `data/deeptip/${f}`);
}

// js/plugins.js: keep every other plugin and its order. The example replaces the DeepTip entries;
// --plugin-only adds DeepTip only when it is missing, so your parameters survive an update.
const readPlugins = (file) => {
  const src = readFileSync(file, "utf8");
  return JSON.parse(src.slice(src.indexOf("["), src.lastIndexOf("]") + 1));
};
const pluginsFile = join(project, "js", "plugins.js");
const existing = existsSync(pluginsFile) ? readPlugins(pluginsFile) : [];
let ours = readPlugins(join(here, "js", "plugins.js"));
if (pluginOnly) {
  ours = existing.some((p) => p.name === "DeepTip")
    ? []
    : ours
        .filter((p) => p.name === "DeepTip")
        .map((p) => ({ ...p, parameters: { ...p.parameters, fallback: '["en"]', values: "[]" } }));
}
const replaced = new Set(ours.map((p) => p.name));
const list = [...existing.filter((p) => !replaced.has(p.name)), ...ours];
put(
  "js/plugins.js",
  Buffer.from(`// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n${list.map((p) => JSON.stringify(p)).join(",\n")}\n];\n`),
);
console.log(pluginOnly ? "Done. Add your glossary as data/deeptip/<locale>.json." : "Done. Open the project in RPG Maker MZ and start a playtest.");
